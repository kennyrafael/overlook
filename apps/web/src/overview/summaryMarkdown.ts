import type { TaskStatus, WorkSummary } from '@overlook/shared';
import { formatDuration, formatUsd, localDay } from '../format';

export const STATUS_LABEL: Record<TaskStatus, string> = { todo: 'To do', in_progress: 'In progress', done: 'Done' };

/** Monday (local midnight) of the ISO week that contains `d`. */
export function mondayOf(d: Date): Date {
  const m = new Date(d.getFullYear(), d.getMonth(), d.getDate());
  m.setDate(m.getDate() - ((m.getDay() + 6) % 7));
  return m;
}

export function addDays(d: Date, n: number): Date {
  const x = new Date(d);
  x.setDate(x.getDate() + n);
  return x;
}

/** ISO 8601 week number and week-year (the year of the week's Thursday). */
export function isoWeek(d: Date): { year: number; week: number } {
  const t = new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
  t.setUTCDate(t.getUTCDate() + 4 - (t.getUTCDay() || 7));
  const yearStart = Date.UTC(t.getUTCFullYear(), 0, 1);
  return { year: t.getUTCFullYear(), week: Math.ceil(((t.getTime() - yearStart) / 86_400_000 + 1) / 7) };
}

export function weekTitle(monday: Date): string {
  const { year, week } = isoWeek(monday);
  return `Week ${week}, ${year}`;
}

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
/** One line of Markdown: no line breaks, no stray list markers from the plan file. */
const line = (s: string) => s.replace(/\s+/g, ' ').trim();

/** The summary as Markdown for a standup or a note. Costs are estimates and say so. */
export function summaryMarkdown(s: WorkSummary, title: string): string {
  const t = s.totals;
  const out: string[] = [`## ${title} (${s.from} to ${s.to})`, ''];
  const claude = t.sessions
    ? `${plural(t.sessions, 'Claude session')} (${formatDuration(t.durationMs)}, ~${formatUsd(t.costUsd)} estimated)`
    : 'no Claude sessions';
  out.push(`${plural(t.tasksCompleted, 'task')} done · ${t.tasksMoved} moved · ${plural(t.commits, 'commit')} · ${claude}`, '');
  if (!s.projects.length) out.push('_Nothing recorded this week._', '');

  for (const p of s.projects) {
    out.push(`### ${line(p.name)}`, '');
    const board = [
      p.tasksCompleted && `${p.tasksCompleted} done`,
      p.moved.length - p.tasksCompleted > 0 && `${p.moved.length - p.tasksCompleted} moved`,
      p.tasksAdded && `${p.tasksAdded} added`,
      p.tasksRemoved && `${p.tasksRemoved} removed`,
    ].filter(Boolean);
    if (board.length) {
      out.push(`**Board:** ${board.join(', ')}`, '');
      for (const m of p.moved) {
        out.push(m.to === 'done'
          ? `- [x] ${line(m.taskText)}`
          : `- ${line(m.taskText)}: ${STATUS_LABEL[m.from!] ?? m.from} → ${STATUS_LABEL[m.to!] ?? m.to}`);
      }
      if (p.moved.length) out.push('');
    }
    if (p.commits) {
      out.push(`**Commits (${p.commits}):**`, '');
      for (const c of p.recentCommits) out.push(`- ${line(c.subject) || '(no subject)'} (\`${c.hash.slice(0, 7)}\`${c.repo ? `, ${c.repo}` : ''})`);
      if (p.commits > p.recentCommits.length) out.push(`- …and ${p.commits - p.recentCommits.length} more`);
      out.push('');
    }
    if (p.sessions) out.push(`**Claude:** ${plural(p.sessions, 'session')} · ${formatDuration(p.durationMs)} · ~${formatUsd(p.costUsd)} estimated`, '');
  }
  out.push(`_Generated by Overlook on ${localDay(new Date(s.generatedAt))}. Costs are estimates at API list prices._`);
  return out.join('\n') + '\n';
}
