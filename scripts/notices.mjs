// Generates third-party notices from the production dependencies in each package-lock.json:
//   - the app (root lockfile)        → THIRD_PARTY_NOTICES.md (shown in the About dialog)
//   - the landing page (site/)       → site/public/third-party-notices.txt (served with the site)
// Exits with code 1 if a copyleft license (GPL, AGPL, LGPL, SSPL, EUPL...) or an unknown
// license is found, so it can run in CI. Usage: `npm run notices` (add `--check` to only verify).
// The OFL used by fonts is allowed: it covers the font files only, not the code that uses them.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const COPYLEFT = /\b(A?GPL|LGPL|SSPL|EUPL|MPL|CDDL|EPL|OSL|CC-BY-SA)/i;
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

const TARGETS = [
  {
    dir: repo,
    out: 'THIRD_PARTY_NOTICES.md',
    intro: 'Overlook includes the following open-source packages. Their license texts follow.',
  },
  {
    dir: join(repo, 'site'),
    out: join('site', 'public', 'third-party-notices.txt'),
    intro: 'The Overlook website (overlook.agenthub.pt) includes the following open-source packages. Their license texts follow.',
  },
];

/** License field from the lockfile, falling back to the package's own package.json. */
function licenseOf(dir, entry) {
  if (entry.license) return entry.license;
  try {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    if (typeof pkg.license === 'string') return pkg.license;
    if (pkg.license?.type) return pkg.license.type;
    if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  } catch { /* missing package.json: reported as UNKNOWN */ }
  return 'UNKNOWN';
}

function licenseText(dir) {
  if (!existsSync(dir)) return '';
  const file = readdirSync(dir).find((f) => LICENSE_FILE.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : '';
}

// A dual license like "(MIT OR GPL-3.0)" is fine: we choose the permissive option.
const permissiveChoice = (l) => / OR /i.test(l) && l.split(/ OR /i).some((p) => !COPYLEFT.test(p));

let failed = false;
for (const { dir: root, out: outFile, intro } of TARGETS) {
  const lockFile = join(root, 'package-lock.json');
  if (!existsSync(lockFile)) {
    console.error(`${lockFile} is missing; run npm install there first`);
    failed = true;
    continue;
  }
  const lock = JSON.parse(readFileSync(lockFile, 'utf8'));
  const deps = [];
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (!path.includes('node_modules/') || entry.dev || entry.link) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (name.startsWith('@overlook/')) continue; // our own workspaces
    const dir = join(root, path);
    deps.push({ name, version: entry.version, license: licenseOf(dir, entry), text: licenseText(dir) });
  }
  deps.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const problems = deps.filter((d) => d.license === 'UNKNOWN' || (COPYLEFT.test(d.license) && !permissiveChoice(d.license)));

  const counts = {};
  for (const d of deps) counts[d.license] = (counts[d.license] ?? 0) + 1;
  console.log(`${outFile}: ${deps.length} production packages`);
  for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${l}`);

  if (!checkOnly) {
    const out = [
      '# Third-party notices',
      '',
      intro,
      'Generated by `npm run notices`; do not edit by hand.',
      '',
      ...deps.flatMap((d) => [
        `## ${d.name}@${d.version} (${d.license})`,
        '',
        d.text ? '```text\n' + d.text.replace(/```/g, "'''") + '\n```' : '_No license file shipped with this package._',
        '',
      ]),
    ];
    writeFileSync(join(repo, outFile), out.join('\n'));
    console.log(`Wrote ${outFile}`);
  }

  if (problems.length) {
    console.error(`\n${outFile}: licenses that need review:`);
    for (const d of problems) console.error(`  ${d.name}@${d.version}: ${d.license}`);
    failed = true;
  }
}
if (failed) process.exit(1);
